// Finds where each clip of a multi-clip narration starts by matching the first
// narration line under every "## Clip N" heading to the Whisper transcript.
// Usage: node scripts/clip-timings.mjs
//   reads  scripts/alphabay_script.md + public/audio/video2/full.json
//   writes src/video2/clipTimings.ts
import fs from "node:fs";
import { execSync } from "node:child_process";

const FPS = 30;
const script = fs.readFileSync("scripts/alphabay_script.md", "utf8");
const { words } = JSON.parse(fs.readFileSync("public/audio/video2/full.json", "utf8"));
const duration = parseFloat(
  execSync("ffprobe -v error -show_entries format=duration -of csv=p=0 public/audio/video2/full.mp3").toString(),
);

const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, "");
const tokens = words.map((w) => norm(w.text));

// first narration line of each clip
const clips = [];
let current = null;
for (const line of script.split("\n")) {
  const h = line.match(/^## Clip (\d+)\s+[—-]\s+(.*)$/);
  if (h) {
    current = { n: +h[1], title: h[2].trim(), first: null };
    clips.push(current);
  } else if (current && !current.first && line.trim() && !line.startsWith("[VISUAL]")) {
    current.first = line.trim();
  }
}

// fuzzy match: slide over the transcript, score how many of the line's first
// words appear (in order, with small gaps allowed). Search only after the previous clip.
let from = 0;
for (const clip of clips) {
  const want = clip.first.split(/\s+/).map(norm).filter(Boolean).slice(0, 10);
  let best = { score: -1, i: from };
  for (let i = from; i < tokens.length - 3; i++) {
    let score = 0;
    let k = i;
    for (const w of want) {
      for (let j = k; j < Math.min(k + 3, tokens.length); j++) {
        if (tokens[j] === w) {
          score += j === k ? 1 : 0.6;
          k = j + 1;
          break;
        }
      }
    }
    // the very first word matching matters most
    if (tokens[i] === want[0]) score += 1.5;
    if (score > best.score) best = { score, i };
  }
  // Whisper may misspell a name that opens the line ("Cazes" -> "Kazez"):
  // if the match began on the line's second word, step back to include the first.
  if (tokens[best.i] !== want[0] && tokens[best.i] === want[1] && best.i > from) best.i -= 1;
  clip.wordIndex = best.i;
  clip.confidence = +(best.score / (want.length + 1.5)).toFixed(2);
  clip.firstWordSec = words[best.i].start;
  from = best.i + 5;
}

// cut each clip in the middle of the silence before its first word
clips.forEach((clip, idx) => {
  if (idx === 0) {
    clip.startSec = 0;
  } else {
    const prevEnd = words[clip.wordIndex - 1].end;
    clip.startSec = +((prevEnd + clip.firstWordSec) / 2).toFixed(3);
  }
});
clips.forEach((clip, idx) => {
  clip.endSec = idx < clips.length - 1 ? clips[idx + 1].startSec : +duration.toFixed(3);
  clip.startFrame = Math.round(clip.startSec * FPS);
  clip.endFrame = idx < clips.length - 1 ? Math.round(clip.endSec * FPS) : Math.ceil(duration * FPS);
});

const rows = clips
  .map(
    (c) =>
      `  { n: ${c.n}, title: ${JSON.stringify(c.title)}, startFrame: ${c.startFrame}, endFrame: ${c.endFrame}, startSec: ${c.startSec}, endSec: ${c.endSec} },`,
  )
  .join("\n");

fs.mkdirSync("src/video2", { recursive: true });
fs.writeFileSync(
  "src/video2/clipTimings.ts",
  `// Generated by scripts/clip-timings.mjs. Do not edit by hand; re-run the script.
export const VIDEO2_FPS = ${FPS};
export const VIDEO2_FRAMES = ${Math.ceil(duration * FPS)};

export type ClipTiming = {
  n: number;
  title: string;
  /** first frame of the clip in the full video */
  startFrame: number;
  /** first frame after the clip */
  endFrame: number;
  startSec: number;
  endSec: number;
};

export const clipTimings: ClipTiming[] = [
${rows}
];
`,
);

const mmss = (s) => `${Math.floor(s / 60)}:${(s % 60).toFixed(1).padStart(4, "0")}`;
console.log("clip | start   | end     | length | frames        | match | first words heard");
for (const c of clips) {
  const heard = words.slice(c.wordIndex, c.wordIndex + 6).map((w) => w.text).join(" ");
  console.log(
    `${String(c.n).padStart(4)} | ${mmss(c.startSec).padStart(7)} | ${mmss(c.endSec).padStart(7)} | ${(c.endSec - c.startSec).toFixed(1).padStart(5)}s | ${String(c.startFrame).padStart(5)}-${String(c.endFrame).padEnd(5)} | ${c.confidence.toFixed(2)}  | ${heard}`,
  );
}
