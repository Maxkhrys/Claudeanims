// Video 3 (Lapsus$) is narrated in three audio parts. This script:
//   1. merges the Whisper transcripts of whichever parts exist into public/audio/video3/full.json
//      (word times offset so they run continuously), and
//   2. finds where each clip starts by matching the first narration line under every
//      "## Clip N" heading in scripts/lapsus_script.md, and writes src/video3/clipTimings.ts.
// Usage: node scripts/video3-timings.mjs      (re-run whenever a new part is added)
import fs from "node:fs";
import { execSync } from "node:child_process";

const FPS = 30;
const DIR = "public/audio/video3";
// which clips each narration part contains
const PART_CLIPS = [
  [1, 9],
  [10, 18],
  [19, 26],
];

const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, "");
const script = fs.readFileSync("scripts/lapsus_script.md", "utf8").split("\n---\n")[0];

const clips = [];
let current = null;
for (const line of script.split("\n")) {
  const h = line.match(/^## Clip (\d+)\s+[—-]\s+(.*)$/);
  if (h) {
    current = { n: +h[1], title: h[2].trim(), first: null };
    clips.push(current);
  } else if (current && !current.first && line.trim() && !line.startsWith("[")) {
    current.first = line.trim();
  }
}

const parts = [];
const words = [];
let offset = 0;
for (let p = 1; p <= PART_CLIPS.length; p++) {
  const mp3 = `${DIR}/part${p}.mp3`;
  const json = `${DIR}/part${p}.json`;
  if (!fs.existsSync(mp3) || !fs.existsSync(json)) break;
  const dur = parseFloat(execSync(`ffprobe -v error -show_entries format=duration -of csv=p=0 ${mp3}`).toString());
  const frames = Math.round(dur * FPS);
  const startFrame = Math.round(offset * FPS);
  const pw = JSON.parse(fs.readFileSync(json, "utf8")).words.map((w) => ({
    text: w.text,
    start: +(w.start + offset).toFixed(3),
    end: +(w.end + offset).toFixed(3),
  }));
  parts.push({ n: p, file: `audio/video3/part${p}.mp3`, startFrame, frames, startSec: offset, endSec: offset + frames / FPS, wordFrom: words.length, wordTo: words.length + pw.length });
  words.push(...pw);
  offset = (startFrame + frames) / FPS; // keep parts frame-aligned
}
if (!parts.length) throw new Error("No transcribed parts found in " + DIR);
fs.writeFileSync(`${DIR}/full.json`, JSON.stringify({ words }, null, 2));

const tokens = words.map((w) => norm(w.text));
const timed = [];
for (const part of parts) {
  const [a, b] = PART_CLIPS[part.n - 1];
  let from = part.wordFrom;
  for (const clip of clips.filter((c) => c.n >= a && c.n <= b)) {
    if (clip.n === a) {
      clip.wordIndex = part.wordFrom;
      clip.startSec = part.startSec;
      clip.confidence = 1;
    } else {
      const want = clip.first.split(/\s+/).map(norm).filter(Boolean).slice(0, 10);
      let best = { score: -1, i: from };
      for (let i = from; i < part.wordTo - 3; i++) {
        let score = 0;
        let k = i;
        for (const w of want) {
          for (let j = k; j < Math.min(k + 3, part.wordTo); j++) {
            if (tokens[j] === w) {
              score += j === k ? 1 : 0.6;
              k = j + 1;
              break;
            }
          }
        }
        if (tokens[i] === want[0]) score += 1.5;
        if (score > best.score) best = { score, i };
      }
      if (tokens[best.i] !== want[0] && tokens[best.i] === want[1] && best.i > from) best.i -= 1;
      clip.wordIndex = best.i;
      clip.confidence = +(best.score / (want.length + 1.5)).toFixed(2);
      clip.startSec = +((words[best.i - 1].end + words[best.i].start) / 2).toFixed(3);
    }
    clip.part = part.n;
    from = clip.wordIndex + 5;
    timed.push(clip);
  }
}
timed.forEach((clip, i) => {
  const next = timed[i + 1];
  const part = parts[clip.part - 1];
  clip.endSec = next && next.part === clip.part ? next.startSec : +part.endSec.toFixed(3);
  clip.startFrame = Math.round(clip.startSec * FPS);
  clip.endFrame = Math.round(clip.endSec * FPS);
});

const total = parts[parts.length - 1].startFrame + parts[parts.length - 1].frames;
fs.mkdirSync("src/video3", { recursive: true });
fs.writeFileSync(
  "src/video3/clipTimings.ts",
  `// Generated by scripts/video3-timings.mjs. Do not edit by hand; re-run the script.
export const VIDEO3_FPS = ${FPS};
/** length of the narration parts that exist so far */
export const VIDEO3_FRAMES = ${total};
export const VIDEO3_CLIP_COUNT = ${clips.length};

export const audioParts = [
${parts.map((p) => `  { n: ${p.n}, file: ${JSON.stringify(p.file)}, startFrame: ${p.startFrame}, frames: ${p.frames} },`).join("\n")}
];

export type ClipTiming = {
  n: number;
  title: string;
  /** which narration part the clip is in */
  part: number;
  startFrame: number;
  endFrame: number;
  startSec: number;
  endSec: number;
};

/** Only clips whose narration has been recorded and transcribed appear here. */
export const clipTimings: ClipTiming[] = [
${timed.map((c) => `  { n: ${c.n}, title: ${JSON.stringify(c.title)}, part: ${c.part}, startFrame: ${c.startFrame}, endFrame: ${c.endFrame}, startSec: ${c.startSec}, endSec: ${c.endSec} },`).join("\n")}
];
`,
);

const mmss = (s) => `${Math.floor(s / 60)}:${(s % 60).toFixed(1).padStart(4, "0")}`;
console.log("clip | part | start   | end     | length | match | first words heard");
for (const c of timed) {
  const heard = words.slice(c.wordIndex, c.wordIndex + 6).map((w) => w.text).join(" ");
  console.log(`${String(c.n).padStart(4)} | ${String(c.part).padStart(4)} | ${mmss(c.startSec).padStart(7)} | ${mmss(c.endSec).padStart(7)} | ${(c.endSec - c.startSec).toFixed(1).padStart(5)}s | ${c.confidence.toFixed(2)}  | ${heard}`);
}
console.log(`${timed.length} of ${clips.length} clips timed; ${parts.length} of ${PART_CLIPS.length} parts present; total ${mmss(total / FPS)}`);
